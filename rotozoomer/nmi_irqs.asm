irq:
//;-------------------------------------------------------------------------
//; Save the registers
//;-------------------------------------------------------------------------
		pha
		php
		stx _rx
		sty _ry
//;-------------------------------------------------------------------------
//; Stabilize the raster
//;-------------------------------------------------------------------------
		lda $dc04
		and #7
		sta Time_4 + 1
		lda #7
		sec
Time_4:	
		sbc #4
		sta Time_5 + 1

Time_5:
		bpl * + 2
		cmp #$c9
		cmp #$c9
		cmp #$c9
		cmp #$24
		nop

//;-------------------------------------------------------------------------
//; Stable raster here, start the nmi-irq if the raster is on the beginning of the screen
//;-------------------------------------------------------------------------

		lda $d012
		cmp #RasterRow + 8
		bcs StopNMI
		lda _pageflip	//;3	 3
		bmi _page_2	//;2 3	 5  6
		lda #$81	//;2	 7
P2_0:
		sta _p_2 + 1	//;4	11

		lda #$91	//;2	13
P1_0:
		sta _p_1 + 1	//;4	17

		nop		//;2	19
		jmp start_nmi	//;3	22
_page_2:	

		lda #$a1	//;  2	    8
P2_1:
		sta _p_2 + 1	//;  4	   12

		lda #$b1	//;  2	   14
P1_1:
		sta _p_1 + 1	//;  4	   18
		nop		//;  2	   20
		nop		//;  2	   22
start_nmi:
		bit $ea		//;3 3	25 25 

		lda #$11
		sta $dd0e
		lda #$81
		sta $dd0d
		lda $dd0d
//;-------------------------------------------------------------------------
//; Set raster-row for ending the NMI here
//;-------------------------------------------------------------------------
		lda #$f8
		sta $d012
//;-------------------------------------------------------------------------
//; Restore all registers
//;-------------------------------------------------------------------------
		plp
		pla
		ldx _rx
		ldy _ry
//;-------------------------------------------------------------------------
//; Return from irq here
//;-------------------------------------------------------------------------
		asl $d019
		rti
//;-------------------------------------------------------------------------
//; Stop the NMI-irq, play music and stuff
//;-------------------------------------------------------------------------
StopNMI:
		lda _p_2 + 1	//; Restore $d018 for the first row
		sta $d018
		lda #RasterRow
		sta $d012
		lda #$00
		sta $dd0e
		
	
		jsr $1003

		
//;-------------------------------------------------------------------------
//; Restore all registers
//;-------------------------------------------------------------------------
		plp
		pla
		ldx _rx
		ldy _ry
//;-------------------------------------------------------------------------
//; Return from irq here
//;-------------------------------------------------------------------------
		asl $d019
		rti


//;-------------------------------------------------------------------------
//; NMI PER IL VECCHIO CIA
//;-------------------------------------------------------------------------
.align $100
nmiirq_old_cia:
//;-------------------------------------------------------------------------
//; Stabilize the raster
//;-------------------------------------------------------------------------
	sta reg_a + 1
	
	//;nop //;Wasto un altro ciclo
	
	lda $dd04
	eor #$e7
	sta time_6 + 1

time_6:	
	bpl *
	cmp #$c9
	cmp #$c9
	cmp #$24
	nop

//;-------------------------------------------------------------------------
//; Stable raster here, create badline for fli and restore to next badline
//;-------------------------------------------------------------------------
_p_1:	
	lda #$91
	sta $d018
	lda #$3f
	sta $d011
	bit $24
	
	
_p_2:
	lda #$81
	sta $d018
	lda #$3b
	sta $d011
	
//;-------------------------------------------------------------------------
//; Trigger new NMI, restore A and return from IRQ here
//;-------------------------------------------------------------------------
	lda $dd0d
reg_a:	
	lda #0 //;questo non dovrebbe essere come ho cambiato io ?
//;	lda reg_a + 1

	rti
	
	
//;-------------------------------------------------------------------------
//; NMI PER IL VECCHIO CIA
//;-------------------------------------------------------------------------
.align $100
nmiirq_new_cia:
//;-------------------------------------------------------------------------
//; Stabilize the raster
//;-------------------------------------------------------------------------
	sta reg_a_new + 1
	
	nop //;Wasto un altro ciclo
	
	lda $dd04
	eor #$e7
	sta time_6_new + 1

time_6_new:	
	bpl *
	cmp #$c9
	cmp #$c9
	cmp #$24
	nop

//;-------------------------------------------------------------------------
//; Stable raster here, create badline for fli and restore to next badline
//;-------------------------------------------------------------------------
_p_1_new:	
	lda #$91
	sta $d018
	lda #$3f
	sta $d011
_p_2_new:
	lda #$81
	sta $d018
	lda #$3b
	sta $d011
//;-------------------------------------------------------------------------
//; Trigger new NMI, restore A and return from IRQ here
//;-------------------------------------------------------------------------
	lda $dd0d
reg_a_new:	
